CREATE TABLE listing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(255) NOT NULL,
    external_id VARCHAR(255) NOT NULL,
    first_seen_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    removed_at TIMESTAMPTZ,
    CONSTRAINT uq_listing_source_external_id UNIQUE (source, external_id)
);

CREATE TABLE listing_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL,
    payload JSONB NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    fetched_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_listing_snapshot_listing FOREIGN KEY (listing_id) REFERENCES listing (id)
);

CREATE INDEX idx_listing_snapshot_listing_id ON listing_snapshot (listing_id);
