CREATE TABLE listing_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL,
    price_czk NUMERIC,
    size_m2 NUMERIC,
    disposition_code INTEGER,
    disposition_label VARCHAR(20),
    year_built INTEGER,
    floor INTEGER,
    energy_class VARCHAR(5),
    construction_type VARCHAR(50),
    elevator BOOLEAN,
    ownership VARCHAR(10),
    city VARCHAR(255),
    district VARCHAR(255),
    region VARCHAR(255),
    parsed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_listing_detail_listing UNIQUE (listing_id),
    CONSTRAINT fk_listing_detail_listing FOREIGN KEY (listing_id) REFERENCES listing (id)
);
