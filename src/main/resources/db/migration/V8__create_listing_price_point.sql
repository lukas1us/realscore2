-- A listing's asking price over time (TASK-23.1), derived from its listing_snapshot rows by parsing.
-- One row per price change: observed_at is the fetched_at of the first snapshot carrying that price, and snapshots
-- whose price equals the previous point add no row. Rebuilt from all snapshots on every parse, so it is idempotent.
-- Existing listings have no rows until their snapshots are re-parsed (POST /api/parsing/reparse).
CREATE TABLE listing_price_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    price_czk NUMERIC NOT NULL,
    CONSTRAINT fk_listing_price_point_listing FOREIGN KEY (listing_id) REFERENCES listing (id),
    CONSTRAINT uq_listing_price_point_listing_observed_at UNIQUE (listing_id, observed_at)
);
